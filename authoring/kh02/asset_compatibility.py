"""Embed authored compatibility rules, never source asset bytes or patch arrays."""
from __future__ import annotations

import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent
OUTPUT = ROOT.parents[1] / "include/kh02/asset_compatibility.h"


def generated_text() -> str:
    rules = json.loads((ROOT / "asset_compatibility.json").read_text(encoding="utf-8"))
    if rules.get("schema") != "kh02.compatibility_rules.v1":
        raise ValueError("Invalid compatibility rule schema")
    expected = {"schema", "mirror", "cutscene_lighting", "effects_lighting", "navigation", "environments",
                "shared_assets", "navigation_levels", "navigation_data", "property_types", "guards"}
    if set(rules) != expected:
        raise ValueError("Unexpected compatibility rule fields")
    metadata = json.loads((ROOT / "runtime_metadata.json").read_text(encoding="utf-8"))
    rules["native_aliases"] = [row["owner"] + "." + row["name"] for row in metadata["aliases"]]
    for group in ("effects_lighting", "navigation"):
        for row in rules[group].values():
            for span in row["ranges"]:
                if any(len(edit) != 2 for edit in span["floats"]):
                    raise ValueError("Rules must contain only offset and replacement value")
    payload = json.dumps(rules, separators=(",", ":"), sort_keys=True)
    if len(payload) > 128 * 1024:
        raise ValueError("Compatibility rule metadata exceeded its size limit")
    literals = '\n'.join('R"kh02rules(' + payload[i:i + 8000] + ')kh02rules"'
                         for i in range(0, len(payload), 8000))
    return ('// Generated by authoring/kh02/asset_compatibility.py.\n#pragma once\n'
            '#include <string_view>\nnamespace kh02asset {\n'
            'inline constexpr std::string_view compatibility_rules =\n' + literals + ';\n}\n')


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    expected = generated_text()
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text(encoding="utf-8") != expected:
            raise ValueError("Stale KH0.2 compatibility rules; run authoring/kh02/asset_compatibility.py")
    else:
        OUTPUT.write_text(expected, encoding="utf-8", newline="\n")


if __name__ == "__main__":
    main()
