"""Build an original static Scaleform surface for the RAM movie texture.

No game assets or media are inputs. The native engine placeholder is replaced by
GFxMoviePlayer.SetExternalTexture; native menus can draw above this surface.
"""
from pathlib import Path
import hashlib
import json
import struct
import sys

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / 'authoring/kh3/map_overlay'))
import build_chest_icon as swf

OUTPUT = ROOT / 'KH3APProbeCpp/resources/kh02/kh02_movie_surface.swf'
METADATA = ROOT / 'include/kh02/movie_surface_metadata.h'
CLASSES = Path(__file__).with_name('movie_surface_classes.abc')


def build():
    expected_sources = json.loads(CLASSES.with_suffix('.json').read_text())
    if any(hashlib.sha256(Path(__file__).with_name(name).read_bytes()).hexdigest() != digest
           for name, digest in expected_sources.items()):
        raise ValueError('Run compile_movie_surface_classes.py after editing the surface classes')
    width, height = 1920, 1080
    bitmap = struct.pack('<5H', 1, 0, 13, width, height) + b'\x09KH02Frame\x12DefaultTexture.tga'
    shape = struct.pack('<H', 2) + swf.rect(0, width * 20, 0, height * 20)
    shape += b'\x01\x41' + struct.pack('<H', 1) + swf.matrix(scale=20) + b'\x00'
    bits = swf.Bits()
    bits.put(1, 4)
    bits.put(0, 4)
    bits.put(0, 1)
    bits.put(3, 5)
    bits.put(1, 5)
    bits.put(0, 1)
    bits.put(0, 1)
    bits.put(1, 1)
    for dx, dy in [(width * 20, 0), (0, height * 20), (-width * 20, 0), (0, -height * 20)]:
        count = max(2, swf.signed_size((dx, dy)))
        bits.put(1, 1)
        bits.put(1, 1)
        bits.put(count - 2, 4)
        bits.put(0, 1)
        bits.put(dx == 0, 1)
        bits.put(dy if dx == 0 else dx, count)
    bits.put(0, 6)
    body = swf.rect(0, width * 20, 0, height * 20) + struct.pack('<HH', 30 * 256, 1)
    exporter = struct.pack('<HIH', 0x401, 0, 13) + b'\0\x0bKH02Surface' + struct.pack('<H', 0)
    body += swf.tag(1000, exporter)
    body += swf.tag(69, struct.pack('<I', 8))
    body += swf.tag(1009, bitmap)
    body += swf.tag(56, struct.pack('<HH', 1, 1) + b'KH02Frame\0')
    body += swf.tag(32, shape + bits.data())
    classes = CLASSES.read_bytes()
    assert set(swf.ABC(classes).classes) == {'KH02Surface', 'KH02Frame'}
    body += swf.tag(82, struct.pack('<I', 0) + b'KH02Surface\0' + classes)
    body += swf.tag(76, struct.pack('<HH', 2, 0) + b'KH02Surface\0' + struct.pack('<H', 1) + b'KH02Frame\0')
    body += swf.place(2, 1, swf.matrix()) + swf.tag(1) + swf.tag(0)
    return b'GFX\x15' + struct.pack('<I', len(body) + 8) + body


if __name__ == '__main__':
    movie = build()
    OUTPUT.write_bytes(movie)
    METADATA.write_text('// Generated by authoring/kh02/build_movie_surface.py; no game media.\n#pragma once\n'
                        f'namespace kh02movie_metadata {{ inline constexpr unsigned surface_size = {len(movie)}; '
                        '}\n')
    print(f'{OUTPUT}: {len(movie)} bytes')
