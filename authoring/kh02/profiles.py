"""Generate and audit KH0.2 integration profiles against original KH3 host images.

The audit is passive and reads executable files only. Offline matches do not
establish live behavior.
"""
from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path
import struct
import sys

ROOT = Path(__file__).resolve().parents[2]
MANIFEST = Path(__file__).with_suffix(".json")
OUTPUT = ROOT / "KH3APProbeCpp/kh3ap/features/kh02/core/kh02_entries.h"


def render(manifest: dict) -> str:
    lines = ["// Generated by authoring/kh02/profiles.py. Do not edit.", "#pragma once",
             "#include <array>", "#include <cstddef>", "#include <cstdint>", "#include <span>",
             "namespace kh3ap::kh02_native", "{", "    enum class Site : size_t", "    {"]
    lines.extend(f"        {site['id']}," for site in manifest["sites"])
    lines.extend(["        count", "    };", "    struct Entry", "    {",
                  "        uintptr_t egs_rva;", "        uintptr_t steam_rva;",
                  "        std::span<const uint8_t> egs_bytes;", "        std::span<const uint8_t> steam_bytes;",
                  "    };"])
    for site in manifest["sites"]:
        for store in ("egs", "steam"):
            code = bytes.fromhex(site[store]["bytes"])
            if code:
                values = ",".join(f"0x{value:02x}" for value in code)
                lines.append(f"    inline constexpr uint8_t {site['id']}_{store}[]{{{values}}};")
    lines.append(f"    inline constexpr std::array<Entry, {len(manifest['sites'])}> entries{{{{")
    for site in manifest["sites"]:
        spans = [f"{site['id']}_{store}" if site[store]["bytes"] else "{}" for store in ("egs", "steam")]
        lines.append(f"        {{{site['egs']['rva']}, {site['steam']['rva']}, {spans[0]}, {spans[1]}}},")
    lines.extend(["    }};", "}", ""])
    return "\n".join(lines)


def audit(manifest: dict, roots: dict[str, Path]) -> dict:
    # Share the existing PE reader, without loading a game or attaching to it.
    sys.path.insert(0, str(ROOT / "authoring/kh3"))
    from audit_character_profiles import Image, executable

    result = {"schema": "kh3ap.kh02_native_audit_result.v1", "status": "passed",
              "builds": {}, "sites": [], "errors": []}
    for store, root in roots.items():
        image = Image(executable(root))
        identity = {"timestamp": hex(image.timestamp), "image_size": hex(image.image_size),
                    "sha256": hashlib.sha256(image.data).hexdigest()}
        result["builds"][store] = {"path": str(image.path), **identity}
        if identity != manifest["builds"][store]:
            result["errors"].append(f"{store}: executable identity mismatch")
        for site in manifest["sites"]:
            profile = site[store]
            rva = int(profile["rva"], 16)
            code = bytes.fromhex(profile["bytes"])
            matched = 0 < rva < image.image_size and (not code or image.read(rva, len(code)) == code)
            result["sites"].append({"id": site["id"], "store": store, "matched": matched})
            if not matched:
                result["errors"].append(f"{store}:{site['id']}: profile mismatch")
            source = (ROOT / site["source"]).read_text(encoding="utf-8")
            if f"Site::{site['id']}" not in source:
                result["errors"].append(f"{site['id']}: source does not bind the audited site")
        sites = {site["id"]: site[store] for site in manifest["sites"]}
        for relation in manifest.get("relationships", []):
            origin = int(sites[relation["origin"]]["rva"], 16) + relation.get("offset", 0)
            expected = int(sites[relation["target"]]["rva"], 16)
            if relation["kind"] == "rip32":
                actual = origin + relation["instruction_size"] + struct.unpack(
                    "<i", image.read(origin + relation["displacement_offset"], 4))[0]
            else:
                # Original image preferred base, read from its PE optional header.
                pe = struct.unpack_from("<I", image.data, 0x3c)[0]
                base = struct.unpack_from("<Q", image.data, pe + 24 + 24)[0]
                actual = struct.unpack("<Q", image.read(origin, 8))[0] - base
            if actual != expected:
                result["errors"].append(f"{store}:{relation['origin']} does not reference {relation['target']}")
    if not OUTPUT.is_file() or OUTPUT.read_text(encoding="utf-8") != render(manifest):
        result["errors"].append("Generated runtime profile differs from its manifest")
    if result["errors"]:
        result["status"] = "failed"
    return result


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--audit", action="store_true")
    parser.add_argument("--egs-game-dir", type=Path)
    parser.add_argument("--steam-game-dir", type=Path)
    parser.add_argument("--output", type=Path)
    args = parser.parse_args()
    manifest = json.loads(MANIFEST.read_text(encoding="utf-8"))
    if args.audit:
        roots = {store: root for store, root in
                 (("egs", args.egs_game_dir), ("steam", args.steam_game_dir)) if root is not None}
        if not roots:
            parser.error("Select an installation with --egs-game-dir or --steam-game-dir")
        result = audit(manifest, roots)
        if args.output:
            args.output.parent.mkdir(parents=True, exist_ok=True)
            args.output.write_text(json.dumps(result, indent=2) + "\n", encoding="utf-8")
        print(json.dumps({key: result[key] for key in ("status", "errors")}))
        return int(result["status"] != "passed")
    expected = render(manifest)
    if args.check:
        return int(not OUTPUT.is_file() or OUTPUT.read_text(encoding="utf-8") != expected)
    if not OUTPUT.is_file() or OUTPUT.read_text(encoding="utf-8") != expected:
        OUTPUT.write_text(expected, encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
