"""Shared native compatibility and area identities; no source asset payloads.

runtime_metadata.json is authoritative. The generated C++ files keep native
registration order and are checked before building the DLL.
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path
import re
from compatibility_audit import validate_adapter_coverage


ROOT = Path(__file__).resolve().parent
OUTPUT_ROOT = ROOT.parents[1] / 'include/kh02'
PHASES = ('initial', 'after_signs', 'after_enums')


def load_metadata(path: Path = ROOT / 'runtime_metadata.json') -> dict:
    value = json.loads(path.read_text(encoding='utf-8'))
    validate_metadata(value)
    return value


def validate_metadata(value: dict) -> None:
    if set(value) != {'schema', 'aliases', 'areas'} or value['schema'] != 'kh02.runtime_metadata.v1':
        raise ValueError('runtime_metadata_schema')
    identities = set()
    previous_phase = 0
    for row in value['aliases']:
        if set(row) != {'phase', 'owner', 'name', 'prototype', 'handler'} or row['phase'] not in PHASES:
            raise ValueError('compatibility_alias_schema')
        phase = PHASES.index(row['phase'])
        if phase < previous_phase:
            raise ValueError('compatibility_alias_phase_order')
        previous_phase = phase
        if (not re.fullmatch(r'/Script/[A-Za-z_0-9]+\.[A-Za-z_0-9]+', row['owner']) or
                not re.fullmatch(r'[A-Za-z_][A-Za-z_0-9]*', row['name']) or
                not re.fullmatch(r'/Script/[A-Za-z_0-9]+\.[A-Za-z_0-9]+:[A-Za-z_0-9]+', row['prototype'])):
            raise ValueError('compatibility_alias_identity')
        if row['handler'] not in ('nullptr', 'levels_shown') and not re.fullmatch(r'compat_thunk<\d+>', row['handler']):
            raise ValueError('compatibility_alias_handler')
        identity = row['owner'] + '.' + row['name']
        if identity in identities:
            raise ValueError('duplicate_compatibility_alias:' + identity)
        identities.add(identity)
    validate_adapter_coverage(value)
    area_ids = set()
    packages = set()
    for row in value['areas']:
        if (set(row) != {'area', 'title', 'package', 'tag', 'initial_nav', 'selectable'} or
                type(row['area']) is not int or row['area'] < 2 or type(row['selectable']) is not bool or
                not isinstance(row['title'], str) or not row['title'] or
                not re.fullmatch(r'/Game/Maps/[A-Za-z_0-9/]+', row['package']) or
                not re.fullmatch(r'[A-Za-z_0-9]+', row['tag']) or
                not re.fullmatch(r'AP02_dw\d{2}_\d{2}|None', row['initial_nav'])):
            raise ValueError('runtime_area_schema')
        if row['area'] in area_ids or row['package'] in packages:
            raise ValueError('duplicate_runtime_area')
        area_ids.add(row['area'])
        packages.add(row['package'])
    if not any(row['area'] == 2 for row in value['areas']):
        raise ValueError('runtime_default_area_missing')


def generated_files(value: dict) -> dict[str, str]:
    validate_metadata(value)
    aliases = ['// Generated by runtime_metadata.py; edit runtime_metadata.json.\n',
               '// Define KH02_COMPAT_ALIAS(phase, owner, name, prototype, handler) before including.\n']
    for row in value['aliases']:
        aliases.append('KH02_COMPAT_ALIAS(' + row['phase'] + ', L' + json.dumps(row['owner']) + ', L' +
                       json.dumps(row['name']) + ', L' + json.dumps(row['prototype']) + ', ' + row['handler'] + ')\n')

    header = ['// Generated by runtime_metadata.py; edit runtime_metadata.json.\n',
              '#pragma once\n#include <string_view>\n\nnamespace kh02metadata\n{\n',
              '    enum class AliasPhase { initial, after_signs, after_enums };\n',
              '    struct Area\n    {\n',
              '        int area;\n        const wchar_t* title;\n        const wchar_t* package;\n',
              '        const wchar_t* tag;\n        const wchar_t* world;\n        const wchar_t* initial_nav;\n',
              '    };\n\n    inline constexpr Area visited_areas[]{\n']
    for row in value['areas']:
        if row['selectable']:
            world = row['package'] + '.' + row['package'].rsplit('/', 1)[1]
            fields = [row['title'], row['package'], row['tag'], world, row['initial_nav']]
            header.append('        {' + str(row['area']) + ', ' + ', '.join('L' + json.dumps(field) for field in fields) + '},\n')
    header.extend(['    };\n\n', '    inline auto initial_nav(std::wstring_view world) -> std::wstring_view\n    {\n'])
    for row in value['areas']:
        world = row['package'] + '.' + row['package'].rsplit('/', 1)[1]
        header.append('        if (world == L' + json.dumps(world) + ')\n        {\n            return L' +
                      json.dumps(row['initial_nav']) + ';\n        }\n')
    default_nav = next(row['initial_nav'] for row in value['areas'] if row['area'] == 2)
    header.append('        return L' + json.dumps(default_nav) + ';\n    }\n} // namespace kh02metadata\n')
    return {'compatibility_aliases.inc': ''.join(aliases), 'runtime_metadata.h': ''.join(header)}


def require_generated(value: dict, root: Path = OUTPUT_ROOT) -> None:
    for name, expected in generated_files(value).items():
        path = root / name
        if not path.exists() or path.read_text(encoding='utf-8') != expected:
            raise ValueError('stale_runtime_metadata:' + name + '; run authoring/kh02/runtime_metadata.py')


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    value = load_metadata()
    if args.check:
        require_generated(value)
    else:
        for name, text in generated_files(value).items():
            path = OUTPUT_ROOT / name
            if not path.exists() or path.read_text(encoding='utf-8') != text:
                path.write_text(text, encoding='utf-8', newline='\n')
    print(f"KH0.2 runtime metadata: {len(value['aliases'])} aliases, {len(value['areas'])} areas")


if __name__ == '__main__':
    main()
