"""Generate the shared runtime character address table from the audited manifest."""
from __future__ import annotations

import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
MANIFEST = Path(__file__).with_name("character_profiles.json")
OUTPUT = ROOT / "KH3APProbeCpp/kh3ap/features/player/characters/character_entries.h"


def render(manifest: dict) -> str:
    sites = [site for site in manifest["sites"] if site.get("runtime", True)]
    lines = ["// Generated by authoring/kh3/generate_character_profiles.py. Do not edit.",
             "#pragma once", "#include <array>", "#include <cstddef>", "#include <cstdint>", "#include <string_view>",
             "", "namespace kh3ap::character_native", "{", "    enum class Site : size_t", "    {"]
    lines.extend(f"        {site['id']}," for site in sites)
    lines.extend(["        count", "    };", "", "    struct Entry", "    {",
                  "        uintptr_t egs_rva, steam_rva;",
                  "        std::string_view egs_bytes, steam_bytes;", "    };", "",
                  "    inline constexpr std::array entries{"])
    for site in sites:
        def profile(store: str) -> tuple[str, str]:
            item = site.get(store)
            if not item:
                return "0", "std::string_view{}"
            raw = bytes.fromhex(item["bytes"])
            literal = "".join(f"\\x{byte:02x}" for byte in raw)
            return item["rva"], f'std::string_view{{"{literal}", {len(raw)}}}'
        er, eb = profile("egs")
        sr, sb = profile("steam")
        lines.append(f"        Entry{{{er}, {sr}, {eb}, {sb}}}, // {site['id']}")
    lines.extend(["    };", "    static_assert(entries.size() == static_cast<size_t>(Site::count));", "}", ""])
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    result = render(json.loads(MANIFEST.read_text(encoding="utf-8")))
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text(encoding="utf-8") != result:
            parser.exit(1, "Character native runtime table is out of date; regenerate it.\n")
    elif not OUTPUT.exists() or OUTPUT.read_text(encoding="utf-8") != result:
        OUTPUT.write_text(result, encoding="utf-8", newline="\n")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
