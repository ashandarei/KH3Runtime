"""Write/check binary movie patches and their small C++ metadata headers."""
from __future__ import annotations

import argparse
import hashlib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
PROBE = ROOT / 'KH3APProbeCpp'
PATCHES = (
    ('shop_ui/APShopRuntime.as', 'kh3ap/features/moogle_shop/shop_movie_patch_data.h', 'shop_movie_patch_egs.bin'),
    ('shop_ui/APShopRuntime.as', 'kh3ap/features/moogle_shop/shop_movie_patch_steam_data.h', 'shop_movie_patch_steam.bin'),
    ('ingredient_journal/APIngredientJournal.as', 'kh3ap/features/journal/ingredient_journal_movie_data.h', 'ingredient_journal_patch.bin'),
)


def fingerprint(data):
    value = 14695981039346656037
    for byte in data:
        value = ((value ^ byte) * 1099511628211) & ((1 << 64) - 1)
    return value


def source_hash(source):
    return hashlib.sha256(source.read_text(encoding='utf-8').encode('utf-8')).hexdigest()


def write_if_changed(path, data):
    path.parent.mkdir(parents=True, exist_ok=True)
    if not path.exists() or path.read_bytes() != data:
        path.write_bytes(data)


def write_patch_resource(*, header, resource, resource_name, namespace, source,
                         generator, original, result, delta):
    """Keep only our audited copy/literal patch in the DLL, not a stock movie."""
    text = '\n'.join([
        f'// Generated by {generator}. Do not edit.',
        f'// Readable source: {source.relative_to(ROOT).as_posix()}.',
        '// Variable guide: docs/MOVIE_SOURCES.md.',
        '// Binary contains only our helper, constructor hooks, identifiers and encoded sizes.',
        '// All game method bodies and graphics are copied from the runtime movie.',
        '// Helper source SHA256 (LF): ' + source_hash(source),
        '// Original SHA256: ' + hashlib.sha256(original).hexdigest(),
        '// Extended SHA256: ' + hashlib.sha256(result).hexdigest(),
        '// Resource SHA256: ' + hashlib.sha256(delta).hexdigest(),
        '#pragma once', '#include "kh3ap/core/ui/embedded_movie_resource.h"',
        'namespace ' + namespace + ' {',
        f'inline constexpr uint32_t original_size = {len(original)};',
        f'inline constexpr uint32_t patched_size = {len(result)};',
        f'inline constexpr uint64_t original_hash = 0x{fingerprint(original):016x}ULL;',
        f'inline constexpr uint64_t patched_hash = 0x{fingerprint(result):016x}ULL;',
        f'inline constexpr uint32_t delta_size = {len(delta)};',
        'inline auto delta_bytes() -> std::span<const uint8_t> {',
        f'    static const auto bytes = load_embedded_movie_resource(L"{resource_name}", delta_size);',
        '    return bytes;', '}', '}', '',
    ])
    write_if_changed(resource, delta)
    write_if_changed(header, text.encode('utf-8'))


def check_generated():
    for source_name, header_name, resource_name in PATCHES:
        source = Path(__file__).resolve().parent / source_name
        header = (PROBE / header_name).read_text(encoding='utf-8')
        data = (PROBE / 'resources' / resource_name).read_bytes()
        digest = hashlib.sha256(data).hexdigest()
        if '// Resource SHA256: ' + digest not in header:
            raise ValueError(f'Movie patch/header mismatch: {resource_name}; regenerate its patch')
        if f'inline constexpr uint32_t delta_size = {len(data)};' not in header:
            raise ValueError(f'Movie patch size mismatch: {resource_name}; regenerate its patch')
        if '// Helper source SHA256 (LF): ' + source_hash(source) not in header:
            raise ValueError(f'{source_name} changed; regenerate its movie patch')


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', required=True)
    parser.parse_args()
    check_generated()
