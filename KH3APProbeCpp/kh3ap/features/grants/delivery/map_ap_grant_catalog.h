    inline auto runtime_map_ap_grant_safety_label(RuntimeMapApGrantSafety safety) -> std::wstring_view
    {
        switch (safety)
        {
        case RuntimeMapApGrantSafety::Safe:
            return L"safe";
        case RuntimeMapApGrantSafety::Unsafe:
            return L"unsafe";
        default:
            return L"unknown";
        }
    }

    inline auto find_runtime_map_ap_grant_rule(std::wstring_view runtime_context)
            -> const RuntimeMapApGrantRule*
    {
        const RuntimeMapApGrantRule* best_match = nullptr;
        for (const RuntimeMapApGrantRule& rule : s_runtime_map_ap_grant_rules)
        {
            if (!rule.match_substring.empty() &&
                runtime_context.find(rule.match_substring) != std::wstring_view::npos &&
                (!best_match || rule.match_substring.size() > best_match->match_substring.size()))
            {
                // For example, unsafe kg_01_unioncross must take precedence
                // over the shorter safe kg_01 package prefix.
                best_match = &rule;
            }
        }
        return best_match;
    }

    inline auto find_runtime_unsafe_ap_grant_rule(std::wstring_view runtime_context)
            -> const RuntimeMapApGrantRule*
    {
        const RuntimeMapApGrantRule* const rule = find_runtime_map_ap_grant_rule(runtime_context);
        if (!rule || rule->safety != RuntimeMapApGrantSafety::Unsafe)
        {
            return nullptr;
        }
        return rule;
    }
