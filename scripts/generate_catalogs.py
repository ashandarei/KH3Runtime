"""Generate native catalogs from the project's versioned runtime-data export."""
from __future__ import annotations

import argparse
import json
from pathlib import Path
import re

from runtime_ui_catalogs import generated_ui_files


ROOT = Path(__file__).resolve().parents[1]
INPUT = ROOT / "data/runtime-inputs.json"
PROBE = ROOT / "KH3APProbeCpp"
TABLES = {
    "catalog": ("kh3ap/bridge/catalog/catalog_data.h", "kh3ap::native_catalog", "shared_data"),
    "chests": ("kh3ap/bridge/catalog/chest_data.h", "kh3ap::chest_manifest", "shared_data"),
    "locations": ("kh3ap/bridge/catalog/location_catalog_data.h", "kh3ap::json", "location_catalog_data"),
    "randomization": ("kh3ap/features/enemies/randomization_catalog.h", "kh3ap::randomization", "catalog_data"),
}


def generated_files(contract: dict) -> dict[str, str]:
    if set(contract) != {"schema", "limits", "ui", *TABLES} or contract["schema"] != "kh3ap.runtime_inputs.v1":
        raise ValueError("Unsupported native runtime input contract")
    prefix = "// Generated by scripts/generate_catalogs.py from data/runtime-inputs.json; do not edit.\n"
    outputs = {}
    for key, (filename, namespace, variable) in TABLES.items():
        if not isinstance(contract[key], dict):
            raise ValueError(f"Invalid runtime input table: {key}")
        encoded = json.dumps(contract[key], ensure_ascii=True, separators=(",", ":"), sort_keys=key != "randomization")
        chunks = "\n".join(json.dumps(encoded[offset:offset + 4000]) for offset in range(0, len(encoded), 4000))
        outputs[filename] = (prefix + "#pragma once\n#include <string_view>\n"
                             f"namespace {namespace} {{\ninline constexpr std::string_view {variable} =\n"
                             + chunks + ";\n}\n")
    limits = contract["limits"]
    if not isinstance(limits, dict) or not limits:
        raise ValueError("Missing runtime JSON limits")
    if any(not re.fullmatch(r"[a-z][a-z0-9_]*", key) or type(value) is not int or not 0 < value <= 64 * 1024 * 1024
           for key, value in limits.items()):
        raise ValueError("Invalid runtime JSON limit")
    outputs["kh3ap/bridge/serialization/json_limits.h"] = (
        prefix + "#pragma once\n#include <cstddef>\nnamespace kh3ap::json::limits {\n"
        + "".join(f"inline constexpr size_t {key} = {value};\n" for key, value in limits.items()) + "}\n")
    outputs.update(generated_ui_files(contract["ui"]))
    return outputs


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    contract = json.loads(INPUT.read_text(encoding="utf-8"))
    for name, text in generated_files(contract).items():
        path = PROBE / name
        current = path.read_text(encoding="utf-8") if path.exists() else None
        if current == text:
            continue
        if args.check:
            parser.exit(1, f"Stale native catalog: {name}; run scripts/generate_catalogs.py\n")
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8", newline="\n")


if __name__ == "__main__":
    main()
