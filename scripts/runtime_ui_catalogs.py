"""Render owned UI catalogs from the local runtime-data contract."""
from __future__ import annotations

import json
import re


def spot_header(spots):
    lines = ["// Generated by scripts/generate_catalogs.py. Do not hand-edit.",
             "#pragma once", "#include <array>", "#include <string_view>",
             "namespace kh3ap {", "struct IngredientSpotActor { std::wstring_view path, key; };",
             f"inline constexpr std::array<IngredientSpotActor, {sum(len(s['actors']) for s in spots)}> ingredient_spot_actors{{{{"]
    for spot in spots:
        for actor in spot["actors"]:
            lines.append(f'    {{L"{actor}", L"{spot["id"]}"}},')
    lines += ["}};", "}", ""]
    return "\n".join(lines)


def rate_header(rates: dict[str, int]) -> str:
    chance_spots = sorted(key for key, rate in rates.items() if rate < 100)
    lines = ["// Generated by scripts/generate_catalogs.py. Do not hand-edit.",
             "#pragma once", "#include <array>", "#include <string_view>",
             "namespace kh3ap {",
             "// Authored m_GenRate below 100; omit leaf markers on both maps.",
             f"inline constexpr std::array<std::wstring_view, {len(chance_spots)}> ingredient_chance_spots{{{{"]
    lines.extend(f'    L"{key}",' for key in chance_spots)
    lines += ["}};", "}", ""]
    return "\n".join(lines)


def journal_header(entries, reference):
    # A bounded TSV avoids relying on JSON availability in KH3's AVM2 runtime.
    lines = ['\t'.join((entry['id'], entry['name'], entry['icon'],
                          '|'.join(s['world'] + '~' + s['map'] + '~' + s['key'] for s in entry['sources'])))
             for entry in entries]
    if any(any(c in text for c in '\t\n|~') for entry in entries
           for text in (entry['name'], entry['icon'],
                        *(s[k] for s in entry['sources'] for k in ('world', 'map')))):
        raise ValueError('Catalog contains a reserved TSV delimiter')
    locators = [s for entry in entries for s in entry['sources']]
    # MSVC limits one wide literal to 16 KiB. Adjacent literals preserve the
    # constant view without heap allocations or a larger compiler limit.
    chunks = []
    chunk = []
    for line in lines:
        if sum(len(v) + 1 for v in chunk) + len(line) + 1 > 4000:
            chunks.extend(['LR"kh3(', *chunk, ')kh3"'])
            chunk = []
        chunk.append(line)
    chunks.extend(['LR"kh3(', *chunk, ')kh3";'])
    actor_rows = [f'    {{L"{s["key"]}", LR"kh3({"|".join(s["actors"])})kh3"}},' for s in locators]
    labels = []
    for key, value in sorted(reference['minimaps'].items()):
        label = value['area_name'] or value['map_name']
        if '\u00c3' in label:
            label = label.encode('latin1').decode('utf-8')
        labels.append('    {L' + json.dumps(key) + ', L' + json.dumps(label) + '},')
    return '\n'.join([
        '// Generated by scripts/generate_catalogs.py. Do not edit.',
        '#pragma once', '#include <array>', '#include <string_view>', 'namespace kh3ap {',
        'inline constexpr std::wstring_view ingredient_journal_catalog =',
        *chunks,
        'struct IngredientJournalSource { std::wstring_view key, actors; };',
        f'inline constexpr std::array<IngredientJournalSource,{len(locators)}> ingredient_journal_sources{{{{',
        *actor_rows, '}};',
        'struct IngredientJournalMapLabel { std::wstring_view key, label; };',
        f'inline constexpr std::array<IngredientJournalMapLabel,{len(labels)}> ingredient_journal_map_labels{{{{',
        *labels, '}};', '}', '',
    ])


def adversary_header(entries, reference):
    result = journal_header(entries, reference).replace('ingredient_journal', 'adversary_journal').replace('IngredientJournal', 'AdversaryJournal')
    # Enemy source lists are longer than food lists. Split individual MSVC
    # wide literals while preserving the exact concatenated actor paths.
    result = re.sub(r'LR"kh3\((.*?)\)kh3"',
                    lambda match: ' '.join('LR"kh3(' + match[1][i:i+4000] + ')kh3"'
                                          for i in range(0, len(match[1]), 4000)) if len(match[1]) > 4000 else match[0],
                    result, flags=re.S)
    rows = [f'    {{L"{e["id"]}", {{{", ".join(map(str, e["enemy_ids"]))}}}, {len(e["enemy_ids"])}}},' for e in entries]
    return result.replace('\n}\n', '\nstruct AdversaryJournalIdentity { std::wstring_view row; std::array<int,4> ids; int count; };\n' +
                          f'inline constexpr std::array<AdversaryJournalIdentity,{len(entries)}> adversary_journal_identities{{{{\n' + '\n'.join(rows) + '\n}};\n}\n')


def weapon_header(entries):
    lines = ["// Generated by scripts/generate_catalogs.py from data/runtime-inputs.json; do not edit.",
             "#pragma once", "#include <array>", "namespace kh3ap {",
             "struct AlternateWeaponDisplay { const wchar_t *row, *token, *help; };",
             f"inline constexpr std::array<AlternateWeaponDisplay, {len(entries)}> alternate_weapon_displays{{{{"]
    for entry in entries:
        values = [entry["row"], entry["token"], "kh3_item.weapon.ap_detail_" + entry["key"]]
        lines.append("    {" + ", ".join("L" + json.dumps(value) for value in values) + "},")
    return "\n".join([*lines, "}};", "}", ""])


def chest_journal_header(locations, sources):
    expected = {v['source_id'].removeprefix('Treasure:') for v in locations.values()
                if v['type'] in ('treasure', 'kh02_chest')}
    if set(sources) != expected:
        raise ValueError('Chest map sources must cover exactly the native and imported chest catalog')
    for identity, actors in sources.items():
        if not actors or len(set(actors)) != len(actors) or any(
                not re.fullmatch(r'/Game/(?:Levels|Zevels)/[^\s|~\t]+:PersistentLevel\.[A-Za-z0-9_]+', actor)
                for actor in actors):
            raise ValueError(f'Invalid chest map source: {identity}')
    entries = []
    for row in locations.values():
        if row['type'] not in ('treasure', 'kh02_chest', 'melody_of_memory'):
            continue
        identity = row['source_id'].removeprefix('Treasure:')
        description = row.get('location_description', row['ap_location_name'])
        name = description.split(' (')[0]
        world = row['world']
        if row['type'] == 'kh02_chest':
            world, name = row['ap_location_name'].rsplit(' - ', 1)
        elif row['type'] == 'melody_of_memory':
            name = 'Melody Chest'
        fields = (identity, name, world, description)
        if any(any(c in value for c in '\t\n\r|~') for value in fields):
            raise ValueError('Chest journal contains a reserved delimiter')
        entries.append((*fields, '|'.join(sources.get(identity, ()))))
    if len({row[0] for row in entries}) != len(entries):
        raise ValueError('Duplicate chest journal identity')
    # Preserve the familiar numbered treasure order within each world.
    entries.sort(key=lambda row: (row[2], [int(v) if v.isdigit() else v for v in re.split(r'(\d+)', row[1])]))
    return '\n'.join([
        '// Generated by scripts/generate_catalogs.py from data/runtime-inputs.json',
        '// and data/chest-journal-sources.json. Do not edit.',
        '#pragma once', '#include <array>', '#include <string_view>', 'namespace kh3ap {',
        'struct ChestJournalEntry { std::wstring_view id, name, world, description, actors; bool has_map; };',
        f'inline constexpr std::array<ChestJournalEntry, {len(entries)}> chest_journal_entries{{{{',
        # The Final World has no native NaviMapData row or map texture.
        *('    {' + ', '.join('L' + json.dumps(v, ensure_ascii=True) for v in row) +
          ', ' + ('false' if row[0] == 'EW_LBOX_001' else 'true') + '},' for row in entries),
        '}};', '}', '',
    ])


def generated_ui_files(data):
    if set(data) != {"spots", "rates", "ingredients", "adversaries", "minimaps", "weapons"}:
        raise ValueError("Unsupported UI catalog input contract")
    reference = {"minimaps": data["minimaps"]}
    return {
        "kh3ap/features/ingredients/ingredient_spots.h": spot_header(data["spots"]),
        "kh3ap/features/ingredients/ingredient_spawn_rates.h": rate_header(data["rates"]),
        "kh3ap/features/journal/ingredient_journal_catalog.h": journal_header(data["ingredients"], reference),
        "kh3ap/features/journal/adversary_journal_catalog.h": adversary_header(data["adversaries"], reference),
        "kh3ap/features/kh02/ui/alternate_weapon_catalog.h": weapon_header(data["weapons"]),
    }
